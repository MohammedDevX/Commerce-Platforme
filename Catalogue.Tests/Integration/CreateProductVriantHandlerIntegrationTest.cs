using Castle.Components.DictionaryAdapter.Xml;
using Castle.DynamicProxy.Generators;
using Catalogue.Application.Common.Abstractions.Persistence;
using Catalogue.Application.ProductVariants.Create;
using Catalogue.Domaine.Entities;
using Catalogue.Domaine.Entities.ValueObjects;
using Catalogue.Infrastructure.Persistence;
using Catalogue.Infrastructure.Persistence.Repositories;
using Catalogue.Tests.Infrastructure.Fixtures;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage;

namespace Catalogue.Tests.Integration
{
    public class CreateProductVriantHandlerIntegrationTest : IClassFixture<CatalogueDatabaseFixture>
    {
        private readonly CatalogueDatabaseFixture _fixture;

        public CreateProductVriantHandlerIntegrationTest(CatalogueDatabaseFixture fixture)
        {
            _fixture = fixture;
        }

        [Fact]
        public async Task Add_ProductVariant_In_Database_Integration_Test()
        {
            await using var context = _fixture.CreateDbContext();
            CancellationToken ct = CancellationToken.None;
            await using var transaction = await context.Database.BeginTransactionAsync(ct);

            var company = new Company("Razor");
            var produit = new Product(company.Id, "Razor mouse");

            context.Companies.Add(company);
            context.Products.Add(produit);
            await context.SaveChangesAsync(ct);

            var money = new Money(140m);
            var sku = new Sku("RAZOR-101-MOUSE");
            var createProductVariantCommand = new CreateProductVariantCommand
                (produit.Id, money.Price, sku.SKU);

            var handler = new CreateProductVariantHandler(
                new ProductRepository(context),
                new ProductVariantRepository(context),
                new UnitOfWork(context)
                );

            /* 
             * To fix the probleme of DbUpdateConcurrencyException() we should to understand that the product 
             * is already tracked by the Change Tracker so whene we made product.AddProductVariant(sku, price) 
             * the handler the variant is added to memory of aggregat Product so EF should track this object 
             * by defaut the domaine Variant create the Id of the variant so EF consults propery Id of Variant
             * and he makes a comparaison if (id is Guid.Empty) => status of the variant in change tracker is 
             * (Added), if the Id contain a value so he considers that the variant already exite in DB so he sets 
             * the status into (Modified), and EF try to made an update requeste on Variant but he but he does 
             * not find the variant in DB and he throw an exception.
             * Solution : To fix this probleme we should to add configuration in ModelBuilder of ProductVariant
             * builder.Property(v => v.Id).ValueGeneratedNever(); => like that the EF understand that the ID 
             * is generated by the code c#
             */
            await handler.Handle(createProductVariantCommand, ct);

            // Get the Saved product to check if persistence work sucessfully

            // To let context2 join the transaction of context we should to create new context that use the
            // same sql connection used by context, so create use DbContextOptionsBuilder() and we passe the 
            // connection to UseSqlServer(connection)
            var options = new DbContextOptionsBuilder<CatalogueDbContext>()
                .UseSqlServer(context.Database.GetDbConnection())
                .Options;

            var context2 = new CatalogueDbContext(options);

            await context2.Database.UseTransactionAsync(transaction.GetDbTransaction());

            var product = await context2.Products
                .Include(p => p.ProductVariants)
                .FirstOrDefaultAsync(p => p.Id == createProductVariantCommand.ProductId, ct);
            var variant = new ProductVariantRepository(context2);

            Assert.NotNull(product);
            Assert.Single(product.ProductVariants);
            Assert.True(await variant.ExistsSkuForProductAsync(sku.SKU, createProductVariantCommand.ProductId, ct));

            await transaction.RollbackAsync(ct);
        }
    }
}
